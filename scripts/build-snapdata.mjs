// Generate data/snapshots.mjs from fixtures/*.json so the web server and tests
// can import real captured snapshots as plain ESM (no filesystem at request time).
// Run manually after capturing fixtures, and automatically via `prebuild`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const fixtureDir = path.join(root, 'fixtures');
const outFile = path.join(root, 'data', 'snapshots.mjs');

const files = fs.readdirSync(fixtureDir).filter((f) => f.endsWith('.json'));
const snapshots = [];
for (const f of files) {
  const bundle = JSON.parse(fs.readFileSync(path.join(fixtureDir, f), 'utf8'));
  for (const s of bundle.snapshots || []) snapshots.push({ market: s.market, symbol: s.symbol, observedAt: s.observedAt, reads: s.reads });
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
const body =
  '// GENERATED by scripts/build-snapdata.mjs — do not edit by hand.\n' +
  `// ${files.length} fixture file(s): ${files.join(', ')}\n` +
  `export const snapshots = ${JSON.stringify(snapshots, null, 1)};\n`;
fs.writeFileSync(outFile, body, 'utf8');
console.log(`Wrote ${outFile} (${snapshots.length} snapshots from ${files.join(', ')})`);
